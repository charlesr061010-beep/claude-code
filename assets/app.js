  function indexData() {
    D.prompts.forEach(function (p, i) { PROMPT_INDEX[p.id] = i; });
    SEARCH = D.players.map(function (p) {
      var n = norm(p[0]);
      return { n: n, c: n.replace(/ /g, ''), toks: n.split(' ') };
    });
  }

  // Map playerIndex -> { t: tier, r: rank } for one prompt.
  function answersFor(pi) {
    if (answerCache[pi]) return answerCache[pi];
    var m = new Map();
    var a = D.prompts[pi].a;
    for (var i = 0; i < a.length; i++) m.set(a[i] >> 3, { t: a[i] & 7, r: i + 1 });
    answerCache[pi] = m;
    return m;
  }

  function search(q) {
    q = norm(q).replace(/\b(jr|sr|ii|iii|iv)\b/g, ' ').replace(/\s+/g, ' ').trim();
    if (q.length < 2) return [];
    var qt = q.split(' ');
    var qc = q.replace(/ /g, '');
    var last = qt[qt.length - 1];
    var hits = [];
    for (var i = 0; i < SEARCH.length; i++) {
      var e = SEARCH[i];
      var score = -1;
      if (e.n === q) score = 100;
      else {
        var all = true;
        for (var k = 0; k < qt.length && all; k++) {
          var tok = qt[k], found = false;
          for (var j = 0; j < e.toks.length; j++) { if (e.toks[j].lastIndexOf(tok, 0) === 0) { found = true; break; } }
          all = found;
        }
        if (all) {
          score = 50;
          if (e.n.lastIndexOf(q, 0) === 0) score += 15;
          if (e.toks[e.toks.length - 1].lastIndexOf(last, 0) === 0) score += 8;
        } else if (qc.length >= 4 && e.c.indexOf(qc) >= 0) score = 20;
      }
      if (score >= 0) hits.push([score, i]);
    }
    hits.sort(function (a, b) { return b[0] - a[0] || a[1] - b[1]; });
    return hits.slice(0, 8).map(function (h) { return h[1]; });
  }

  // ------------------------------------------------------------------
  // Choosing a game's seven prompts
  // ------------------------------------------------------------------
  var POOLS = null;
  function pools() {
    if (POOLS) return POOLS;
    POOLS = {};
    Object.keys(GROUPS).forEach(function (g) { POOLS[g] = []; });
    D.prompts.forEach(function (p, i) {
      Object.keys(GROUPS).forEach(function (g) { if (GROUPS[g].indexOf(p.c) >= 0) POOLS[g].push(i); });
    });
    return POOLS;
  }

  function pickGame(seed) {
    var r = rng(seed);
    var P = pools();
    var diffs = DIFFS.slice();
    for (var i = diffs.length - 1; i > 0; i--) { var j = Math.floor(r() * (i + 1)); var t = diffs[i]; diffs[i] = diffs[j]; diffs[j] = t; }
    var chosen = [], usedTeams = {};
    SLOTS.forEach(function (slot, s) {
      var group = slot[Math.floor(r() * slot.length)];
      var ok = function (pi) {
        if (chosen.indexOf(pi) >= 0) return false;
        var tm = D.prompts[pi].tm || [];
        for (var k = 0; k < tm.length; k++) if (usedTeams[tm[k]]) return false;
        return true;
      };
      var pool = P[group].filter(ok);
      var pref = pool.filter(function (pi) { return D.prompts[pi].d === diffs[s]; });
      var from = pref.length ? pref : pool;
      var pick = from[Math.floor(r() * from.length)];
      chosen.push(pick);
      (D.prompts[pick].tm || []).forEach(function (t) { usedTeams[t] = true; });
    });
    // Easier innings first, so the game builds.
    return chosen
      .map(function (pi, k) { return { pi: pi, k: k }; })
      .sort(function (a, b) { return D.prompts[a.pi].d - D.prompts[b.pi].d || a.k - b.k; })
      .map(function (x) { return D.prompts[x.pi].id; });
  }

