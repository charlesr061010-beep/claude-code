  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }
  function norm(s) {
    return String(s).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
      .replace(/[.'’`]/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
  }
  function hashStr(s) {
    var h = 2166136261 >>> 0;
    for (var i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
    return h >>> 0;
  }
  function rng(seed) {
    var a = seed >>> 0;
    return function () {
      a = (a + 0x6D2B79F5) >>> 0;
      var t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  function ordinal(n) {
    var s = ['th', 'st', 'nd', 'rd'], v = n % 100;
    return n + (s[(v - 20) % 10] || s[v] || s[0]);
  }
  function fmt(n) { return n.toLocaleString('en-US'); }
  function plural(n, word) { return n + ' ' + word + (n === 1 ? '' : 's'); }
  function player(i) { return D.players[i]; }
  function playerName(i) { return D.players[i][0]; }
  function playerMeta(i) {
    var p = D.players[i];
    var yrs = p[1] === p[2] ? String(p[1]) : p[1] + '–' + p[2];
    return (p[3] ? p[3] + ' · ' : '') + yrs;
  }
  function tierOf(t) { return t < 0 ? K : TIERS[t]; }
  function distanceLabel(ft) {
    var lab = DISTANCE_LABELS[0][1];
    DISTANCE_LABELS.forEach(function (d) { if (ft >= d[0]) lab = d[1]; });
    return lab;
  }
  function todayNum() {
    var d = new Date();
    var local = Date.UTC(d.getFullYear(), d.getMonth(), d.getDate());
    return Math.max(1, Math.floor((local - EPOCH) / 864e5) + 1);
  }
  function msToMidnight() {
    var d = new Date();
    var m = new Date(d.getFullYear(), d.getMonth(), d.getDate() + 1);
    return m - d;
  }
