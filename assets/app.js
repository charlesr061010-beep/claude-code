  // ---------- pitch clock ----------
  function startClock() {
    stopClock();
    var tick = function () {
      var left = Math.max(0, G.deadline - Date.now());
      var secs = Math.ceil(left / 1000);
      var num = $('#clock-num'), fill = $('#clock-fill'), clock = $('#clock');
      if (num) num.textContent = secs;
      if (fill) fill.style.transform = 'scaleX(' + (left / (CLOCK * 1000)) + ')';
      if (clock) clock.classList.toggle('hurry', secs <= 7);
      if (left <= 0) { stopClock(); answer(-1, true); }
    };
    tick();
    timer = setInterval(tick, 100);
  }
  function stopClock() { if (timer) { clearInterval(timer); timer = null; } }

  // ---------- autocomplete ----------
  function wireSearch() {
    var input = $('#guess'), list = $('#results');
    var items = [], sel = 0;
    var used = usedPlayers();

    function draw() {
      if (!input.value.trim()) { list.innerHTML = ''; input.setAttribute('aria-expanded', 'false'); return; }
      if (!items.length) {
        list.innerHTML = input.value.trim().length >= 2 ? '<li class="none" role="option" aria-disabled="true">No player by that name</li>' : '';
        input.setAttribute('aria-expanded', String(!!list.innerHTML));
        return;
      }
      list.innerHTML = items.map(function (pid, k) {
        var u = used.indexOf(pid) >= 0;
        return '<li role="option" id="opt-' + k + '" data-pid="' + pid + '" aria-selected="' + (k === sel) + '"' +
          (u ? ' class="used" aria-disabled="true"' : '') + '>' +
          '<span class="nm">' + esc(playerName(pid)) + '</span>' +
          '<span class="meta">' + (u ? 'already used' : esc(playerMeta(pid))) + '</span></li>';
      }).join('');
      input.setAttribute('aria-expanded', 'true');
      input.setAttribute('aria-activedescendant', 'opt-' + sel);
    }
    function choose(pid) {
      if (pid == null || used.indexOf(pid) >= 0) return;
      answer(pid, false);
    }
    input.addEventListener('input', function () {
      items = search(input.value);
      sel = 0;
      while (sel < items.length - 1 && used.indexOf(items[sel]) >= 0) sel++;
      draw();
    });
    input.addEventListener('keydown', function (e) {
      if (e.key === 'ArrowDown' && items.length) { sel = (sel + 1) % items.length; draw(); e.preventDefault(); }
      else if (e.key === 'ArrowUp' && items.length) { sel = (sel - 1 + items.length) % items.length; draw(); e.preventDefault(); }
      else if (e.key === 'Enter') { e.preventDefault(); if (items.length) choose(items[sel]); }
      else if (e.key === 'Escape') { input.value = ''; items = []; draw(); }
    });
    list.addEventListener('mousedown', function (e) { e.preventDefault(); });
    list.addEventListener('click', function (e) {
      var li = e.target.closest('li[data-pid]');
      if (li) choose(Number(li.getAttribute('data-pid')));
    });
  }

  // ---------- scoring an answer ----------
  function answer(pid, timedOut) {
    if (locked || G.phase !== 'pitch') return;
    locked = true;
    stopClock();
    var pi = promptAt(G.cur);
    var hit = pid >= 0 ? answersFor(pi).get(pid) : null;
    var rec = {
      p: pid, t: hit ? hit.t : -1, pts: hit ? TIERS[hit.t].pts : 0,
      r: hit ? hit.r : 0, n: D.prompts[pi].a.length, timeout: !!timedOut
    };
    G.inn[G.cur] = rec;
    G.phase = 'result';
    persist();
    render();
  }

  function diamond(t) {
    var tier = tierOf(t);
    var n = tier.bases;
    var color = t < 0 ? 'var(--strike)' : 'var(--t-' + tier.key + ')';
    var pts = [[50, 88], [88, 50], [50, 12], [12, 50]];
    var s = '<svg class="diamond" viewBox="0 0 100 100" aria-hidden="true" style="--run:' + color + '">';
    s += '<polygon class="field" points="50,88 88,50 50,12 12,50"/>';
    if (n >= 4) s += '<polygon class="inside" points="50,88 88,50 50,12 12,50"/>';
    for (var i = 0; i < 4; i++) {
      var a = pts[i], b = pts[(i + 1) % 4];
      s += '<line class="path' + (i < n ? ' on' : '') + '" x1="' + a[0] + '" y1="' + a[1] + '" x2="' + b[0] + '" y2="' + b[1] + '"/>';
    }
    for (var k = 1; k <= 3; k++) {
      var c = pts[k];
      s += '<rect class="base' + (k <= n ? ' on' : '') + '" x="' + (c[0] - 6) + '" y="' + (c[1] - 6) + '" width="12" height="12" transform="rotate(45 ' + c[0] + ' ' + c[1] + ')"/>';
    }
    s += '<polygon class="base' + (n >= 4 ? ' on' : '') + '" points="44,84 56,84 56,90 50,95 44,90"/>';
    if (t < 0) s += '<text class="runk" x="50" y="62" text-anchor="middle">K</text>';
    return s + '</svg>';
  }

  function nameChips(list) {
    return '<ul class="names">' + list.map(function (x) {
      return '<li title="' + esc(playerMeta(x.p)) + '"><span class="dot tier-' + TIERS[x.t].key + '"></span>' + esc(playerName(x.p)) + '</li>';
    }).join('') + '</ul>';
  }

  // Popular answers + the best-known home-run answers, for the reveal.
  function highlights(pi) {
    var a = D.prompts[pi].a;
    var common = [], deep = [];
    for (var i = 0; i < a.length && common.length < 5; i++) {
      if ((a[i] & 7) !== 1) common.push({ p: a[i] >> 3, t: a[i] & 7 });
    }
    var best = 5;
    for (var tt = 5; tt >= 3; tt--) {
      var any = false;
      for (var q = 0; q < a.length; q++) if ((a[q] & 7) === tt) { any = true; break; }
      if (any) { best = tt; break; }
    }
    for (var j = 0; j < a.length && deep.length < 5; j++) {
      if ((a[j] & 7) === best) deep.push({ p: a[j] >> 3, t: best });
    }
    return { common: common, deep: deep, deepTier: best };
  }

  function wrongHint(pid, pi) {
    var name = playerName(pid);
    var hint = esc(name) + ' (' + esc(playerMeta(pid)) + ") doesn't fit this prompt.";
    var twin = null;
    answersFor(pi).forEach(function (v, k) { if (!twin && k !== pid && playerName(k) === name) twin = k; });
    if (twin !== null) hint += ' Wrong one, though: the ' + esc(name) + ' who fits played ' + esc(playerMeta(twin).replace(/^[^·]*· /, '')) + '.';
    return hint;
  }

  function renderResult() {
    var pi = promptAt(G.cur);
    var p = D.prompts[pi];
    var x = G.inn[G.cur];
    var t = tierOf(x.t);
    var who, why;
    if (x.t >= 0) {
      who = esc(playerName(x.p));
      why = '#' + fmt(x.r) + ' most common of ' + fmt(x.n) + ' valid answers. ' + esc(t.blurb);
    } else if (x.timeout) {
      who = 'Pitch clock violation';
      why = 'Time ran out. ' + fmt(x.n) + ' players would have worked.';
    } else if (x.p < 0) {
      who = 'Took strike three';
      why = fmt(x.n) + ' players would have worked.';
    } else {
      who = 'Swing and a miss';
      why = wrongHint(x.p, pi);
    }
    var h = highlights(pi);
    var last = G.cur === INNINGS - 1;
    $('#stage').innerHTML =
      '<article class="card result">' +
        promptHeader(p) +
        '<h2 class="prompt" style="font-size:clamp(1.3rem,4.4vw,1.75rem)">' + esc(p.t) + '</h2>' +
        '<div class="verdict">' + diamond(x.t) +
          '<div><span class="verdict-tier pop tier-' + t.key + '">' + t.label + '</span>' +
          '<span class="verdict-pts">+' + x.pts + ' ft</span>' +
          '<p class="verdict-who">' + who + '</p><p class="verdict-why">' + why + '</p></div>' +
        '</div>' +
        '<div class="answers"><h3>Most common answers</h3>' + nameChips(h.common) + '</div>' +
        '<div class="answers"><h3>' + (h.deepTier === 5 ? 'Home runs you could have hit' : TIERS[h.deepTier].label + 's you could have hit') + '</h3>' + nameChips(h.deep) + '</div>' +
        '<div class="row"><button class="btn primary" id="btn-next" type="button">' + (last ? 'See the box score' : 'Next inning') + '</button></div>' +
      '</article>';
    $('#btn-next').addEventListener('click', nextInning);
    $('#btn-next').focus({ preventScroll: true });
  }

  function nextInning() {
    if (G.cur < INNINGS - 1) {
      G.cur++;
      startInning();
    } else {
      G.phase = 'final';
      recordFinish();
      persist();
      render();
    }
  }

